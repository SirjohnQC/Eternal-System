def paint(rows: str):
    lines = [ln.rstrip("\n") for ln in rows.strip("\n").split("\n")]
    # pad to 32x32
    while len(lines) < 32:
        lines.append("." * 32)
    lines = [ln.ljust(32, ".")[:32] for ln in lines[:32]]
    return [[PAL.get(ch, PAL["."]) for ch in ln] for ln in lines]


def write_png(path: Path, img):
    h, w = len(img), len(img[0])
    raw = b"".join(b"\x00" + b"".join(struct.pack("BBBB", *p) for p in row) for row in img)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(
            ">I", zlib.crc32(tag + data) & 0xFFFFFFFF
        )

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def sheet(items):
    cols, pad, cell = 4, 4, 32
    rows_n = (len(items) + cols - 1) // cols
    W = cols * (cell + pad) + pad
    H = rows_n * (cell + pad) + pad
    bg = (10, 6, 18, 255)
    img = [[bg for _ in range(W)] for _ in range(H)]
    for i, spr in enumerate(items):
        ox = pad + (i % cols) * (cell + pad)
        oy = pad + (i // cols) * (cell + pad)
        for y in range(32):
            for x in range(32):
                p = spr[y][x]
                img[oy + y][ox + x] = p if p[3] else (16, 10, 28, 255)
    return img


